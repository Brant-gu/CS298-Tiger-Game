from __future__ import annotations

import platform
import subprocess
from dataclasses import asdict

from tiger_game.model import TigerGame
from tiger_game.solver import TigerSolver, best_actions, q_values, value


PAPER_MATCHED = {
    (0.85, 1),
    (0.85, 2),
    (0.85, 3),
    (0.85, 4),
}


def get_git_commit(cwd: str = ".") -> str:
    try:
        result = subprocess.run(
            ["git", "rev-parse", "HEAD"],
            cwd=cwd,
            check=True,
            capture_output=True,
            text=True,
        )
        return result.stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def validation_status(accuracy: float, horizon: int) -> tuple[str, str]:
    if (accuracy, horizon) in PAPER_MATCHED:
        return (
            "paper_match",
            "Finite-horizon policy structure matches the original Tiger Game papers.",
        )
    return (
        "exploratory",
        "Result is generated by the exact solver but is not a directly published benchmark.",
    )


def run_experiments(
    probabilities: list[float],
    horizons: list[int],
    belief_left: float = 0.5,
    git_commit: str = "unknown",
) -> list[dict[str, object]]:
    rows: list[dict[str, object]] = []
    for probability in probabilities:
        solver = TigerSolver(TigerGame(p_correct=probability))
        for horizon in horizons:
            result = solver.solve_with_metrics(horizon)
            vectors = result.vectors
            q_at_belief = q_values(vectors, belief_left)
            status, notes = validation_status(probability, horizon)
            rows.append(
                {
                    "run_id": f"p{int(round(probability * 100)):03d}-h{horizon}-exact",
                    "parameters": {
                        "accuracy": probability,
                        "horizon": horizon,
                        "discount": solver.game.discount,
                        "reward_preset": "paper_standard",
                        "solver_mode": "exact_alpha",
                    },
                    "metrics": {
                        **asdict(result.metrics),
                        "value_at_belief": value(vectors, belief_left),
                        "best_actions_at_belief": [
                            action.value for action in best_actions(vectors, belief_left)
                        ],
                        "q_values_at_belief": {
                            action.value: q_at_belief[action]
                            for action in q_at_belief
                        },
                    },
                    "validation": {
                        "status": status,
                        "notes": notes,
                    },
                    "reproducibility": {
                        "git_commit": git_commit,
                        "python_version": platform.python_version(),
                        "seed": None,
                    },
                    "alpha_vectors": [
                        {
                            "action": vector.action.value,
                            "values": list(vector.values),
                        }
                        for vector in vectors
                    ],
                }
            )
    return rows


def build_dashboard_payload(
    probabilities: list[float],
    horizons: list[int],
    belief_left: float = 0.5,
    git_commit: str = "unknown",
) -> dict[str, object]:
    runs = run_experiments(
        probabilities=probabilities,
        horizons=horizons,
        belief_left=belief_left,
        git_commit=git_commit,
    )
    return {
        "default_accuracy": probabilities[0],
        "default_horizon": horizons[min(1, len(horizons) - 1)],
        "belief_left": belief_left,
        "available_accuracies": probabilities,
        "available_horizons": horizons,
        "runs": runs,
    }
